#!/usr/bin/env python3
"""Extract the output chips' per-mode register tables from MVKAVCIO.sys.

AD9889B HDMI transmitter (I2C 0x72): DAT_0007a0f0, 12 modes x 0xb3 entries of {u32 index, u32 value}, loaded by
FUN_000194cc (writable registers only, in table order). Mode from the output format (FUN_00019640):
  0 init, 1 480i, 2 480p, 3 576i, 4 576p, 5 1080i50, 6 1080i60, 7 720p50, 8 720p60, 9 1080p24, 10 1080p25,
  11 1080p30 (no 1080p50/60).
ADV7341 encoder (I2C 0x54): DAT_00076e50, 24 modes x 0x87 u32 values (one per register index), loaded by
FUN_0001d698 (writable registers only); for modes 0 and 6 PWR_MODE = 0xfc afterwards (board flag +0x474 = 1 on the
Mini). Mode (FUN_0001d81c) with the defaults (+0xf4 = 0, +0xf8 = 2, +0xfc = 3):
  480 lines 1, 576 lines 7, 720p50 0x13, 720p60 0x11, 720p59.94 0xf, 1080i60 0xb, 1080i59.94 9, 1080i50 0xd,
  1080p (any) 0x17.
Index -> register address from notes/MVKAVCIO.chipregs.txt (+ the entries its regex misses).
Writes notes/AD9889B.modes.txt, notes/ADV7341.modes.txt, tools/output_modes.py and driver/output_modes.h.
Usage: python3 -I tools/output_tables.py
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, HERE)
from pe import PE  # noqa: E402

pe = PE(os.path.join(ROOT, 'bin', 'MVKAVCIO.sys'))


def off(va):
    for _, v, vs, raw, _ in pe.sections:
        if pe.base + v <= va < pe.base + v + vs:
            return raw + va - pe.base - v
    raise ValueError(hex(va))


def chip_regs(fn, extra):
    regs, cur = dict(extra), None
    for line in open(os.path.join(ROOT, 'notes', 'MVKAVCIO.chipregs.txt')):
        if line.startswith('#'):
            cur = line.split()[1]
        elif cur == fn:
            m = re.search(r'idx=0x(\w+)\s+reg=0x(\w+)\s+size=\d+\s+(RO|RW)\s+(.*)', line)
            if m:
                regs[int(m[1], 16)] = (int(m[2], 16), m[3], m[4].strip())
    return regs


# constructed through FUN_00019a24 (writable), missed by chipregs.py
TX = chip_regs('FUN_0001528c', {0x11: (0x11, 'RW', 'SUBPKT3_SRC'), 0x12: (0x12, 'RW', 'AUDIO CONTROL 3')})
ENC = chip_regs('FUN_0001aa04', {0x13: (0x17, 'RW', 'SOFT_RST')})

o = off(0x7a0f0)
tx = [[struct.unpack_from('<II', pe.data, o + m * 0x598 + 8 * i) for i in range(0xb3)] for m in range(12)]
assert all([a for a, _ in t] == [a for a, _ in tx[0]] for t in tx), 'AD9889B index order differs'
o = off(0x76e50)
enc = [[struct.unpack_from('<I', pe.data, o + (m * 0x87 + i) * 4)[0] for i in range(0x87)] for m in range(24)]

TX_MODES = [[(TX[i][0], v) for i, v in t if TX[i][1] == 'RW'] for t in tx]
ENC_MODES = [[(ENC[i][0], v) for i, v in enumerate(t) if ENC[i][1] == 'RW'] for t in enc]

with open(os.path.join(ROOT, 'notes', 'AD9889B.modes.txt'), 'w') as f:
    f.write('# AD9889B per-mode tables (MVKAVCIO DAT_0007a0f0, FUN_000194cc writes the RW entries in this order)\n')
    f.write('# modes: 0 init, 1 480i, 2 480p, 3 576i, 4 576p, 5 1080i50, 6 1080i60, 7 720p50, 8 720p60, '
            '9 1080p24, 10 1080p25, 11 1080p30\n')
    f.write('# reg rw name%s %s\n' % (' ' * 26, ' '.join('m%-2d' % m for m in range(12))))
    for k, (idx, _) in enumerate(tx[0]):
        reg, rw, name = TX[idx]
        f.write('%02x  %s %-30s %s\n' % (reg, rw, name[:30], ' '.join('%02x ' % t[k][1] for t in tx)))

with open(os.path.join(ROOT, 'notes', 'ADV7341.modes.txt'), 'w') as f:
    f.write('# ADV7341 per-mode tables (MVKAVCIO DAT_00076e50, FUN_0001d698 writes the RW entries in this order)\n')
    f.write('# defaults: 480 lines m1, 576 m7, 720p50 m19 (0x13), 720p60 m17, 1080i60 m11, 1080i50 m13, '
            '1080p m23\n')
    f.write('# reg rw name%s %s\n' % (' ' * 16, ' '.join('m%-2d' % m for m in range(24))))
    for i in range(0x87):
        reg, rw, name = ENC[i]
        f.write('%02x  %s %-20s %s\n' % (reg, rw, name[:20], ' '.join('%02x ' % t[i] for t in enc)))

with open(os.path.join(HERE, 'output_modes.py'), 'w') as f:
    f.write('"""Output chip mode tables, generated by output_tables.py from MVKAVCIO (see there).\n\n'
            'TX_MODES[m] / ENC_MODES[m] = [(reg, value), ...]: the writable registers in the order Windows\n'
            'writes them. TX (AD9889B, I2C 0x72) modes 0-11, ENC (ADV7341, I2C 0x54) modes 0-23.\n"""\n')
    for name, modes in (('TX_MODES', TX_MODES), ('ENC_MODES', ENC_MODES)):
        f.write('%s = [\n' % name)
        for m in modes:
            f.write('    [%s],\n' % ', '.join('(0x%02x, 0x%02x)' % rv for rv in m))
        f.write(']\n')
print('AD9889B: 12 modes x %d writable, ADV7341: 24 modes x %d writable' % (len(TX_MODES[0]), len(ENC_MODES[0])))

with open(os.path.join(ROOT, '..', 'driver', 'output_modes.h'), 'w') as f:
    f.write('/* SPDX-License-Identifier: GPL-2.0 */\n'
            '/*\n * Output chip mode tables (generated by re/tools/output_tables.py from MVKAVCIO, see there):\n'
            ' * {register, value} for the writable registers in the order Windows writes them.\n'
            ' * AD9889B (HDMI out) modes: 0 init, 1 480i, 2 480p, 3 576i, 4 576p, 5 1080i50, 6 1080i60, 7 720p50,\n'
            ' * 8 720p60, 9 1080p24, 10 1080p25, 11 1080p30. ADV7341 (analog out): 480 lines 1, 576 lines 7, 720p50 19,\n'
            ' * 720p60 17, 1080i60 11, 1080i50 13, 1080p 23.\n */\n')
    f.write('#ifndef MXO2_OUTPUT_MODES_H\n#define MXO2_OUTPUT_MODES_H\n\n')
    for name, modes in (('ad9889b_modes', TX_MODES), ('adv7341_modes', ENC_MODES)):
        f.write('static const u8 %s[%d][%d][2] = {\n' % (name, len(modes), len(modes[0])))
        for m in modes:
            f.write('\t{\n')
            for k in range(0, len(m), 8):
                f.write('\t\t%s\n' % ' '.join('{ 0x%02x, 0x%02x },' % rv for rv in m[k:k + 8]))
            f.write('\t},\n')
        f.write('};\n\n')
    f.write('#endif\n')
