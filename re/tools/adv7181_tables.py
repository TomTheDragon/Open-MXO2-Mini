#!/usr/bin/env python3
"""Generate adv7181_modes.py from MVKAVCIO.sys (ADV7181 decoder class, ctor FUN_00025030).

Tables (Ghidra addresses, image base 0x10000): modes DAT_00072520 (14 x 187 dwords), mask DAT_00074e10,
or-bits DAT_000756e0. FUN_0002976c writes, for every writable register index i in order,
(mode[i] & mask[i]) | or[i] after setting PwrManagement (0x0f) bit 7 (reset) and waiting 20 ms.
Register index -> address from notes/MVKAVCIO.chipregs.txt (# FUN_000251d4). Mode selection (vt+0x48 =
0x29224): SD NTSC: input 1 -> 0, 4 -> 1, 2 -> 2; SD PAL (rate code 3): 1 -> 3, 4 -> 4, 2 -> 5;
1080 lines: 29.97 -> 6, 30 -> 7, 25 -> 8; 720p: 59.94 -> 9, 60 -> 10, 50 -> 11 (12/13 unused here).
Usage: python3 -I adv7181_tables.py > adv7181_modes.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe import PE  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
pe = PE(os.path.join(HERE, '..', 'bin', 'MVKAVCIO.sys'))
G = lambda a: a - 0x10000  # noqa: E731  Ghidra address -> RVA
regs = {}
inside = False
for line in open(os.path.join(HERE, '..', 'notes', 'MVKAVCIO.chipregs.txt')):
    if line.startswith('#'):
        inside = line.startswith('# FUN_000251d4')
        continue
    m = re.search(r'idx=0x([0-9a-f]+)\s+reg=0x([0-9a-f]+)\s+size=\d+\s+(\w+)\s+(\S+)', line)
    if inside and m:
        regs[int(m[1], 16)] = (int(m[2], 16), m[3], m[4])
assert len(regs) == 187, len(regs)
mask = [pe.u32(G(0x74e10) + 4 * i) for i in range(187)]
orv = [pe.u32(G(0x756e0) + 4 * i) for i in range(187)]
print('"""ADV7181 decoder mode tables, generated by adv7181_tables.py from MVKAVCIO.sys (see there).')
print('')
print('MODES[i] = [(reg, value), ...] in write order (writable registers only); NAMES[reg] = name."""')
print('NAMES = {%s}' % ', '.join('0x%02x: %r' % (a, n) for i, (a, rw, n) in sorted(regs.items())))
print('MODES = [')
for mo in range(14):
    vals = []
    for i in range(187):
        a, rw, n = regs[i]
        if rw == 'RO':
            continue
        v = (pe.u32(G(0x72520) + 4 * (mo * 187 + i)) & mask[i]) | orv[i]
        vals.append('(0x%02x, 0x%02x)' % (a, v & 0xff))
    print('    [%s],' % ', '.join(vals))
print(']')
