#!/usr/bin/env python3
"""Write driver/adv7181_modes.h: ADV7181 SD tables (modes 0-5: composite / S-video / component, NTSC then PAL),
the hidden-register scripts (MVKAVCIO FUN_00028f04: modes 0/1/3/4 the ADI SD script, 2/5 b7=1b) and the composite
level/filter overrides from analog probes 6/7.
Usage: python3 -I gen_adv7181_header.py > ../../driver/adv7181_modes.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from adv7181_modes import MODES  # noqa: E402
from analog_probe import HIDDEN_SD  # noqa: E402
from analog_probe7 import DEFAULT  # noqa: E402


def table(name, pairs):
    out = ['static const u8 %s[][2] = {' % name]
    for i in range(0, len(pairs), 6):
        out.append('\t' + ' '.join('{ 0x%02x, 0x%02x },' % p for p in pairs[i:i + 6]))
    out.append('};')
    return out


HIDDEN_COMP = [(0xb7, 0x1b)]
lines = ['/* SPDX-License-Identifier: GPL-2.0 */', '/*',
         ' * ADV7181 video decoder tables, generated by re/tools/gen_adv7181_header.py.',
         ' * Modes from MVKAVCIO.sys DAT_00072520 (FUN_0002976c: (mode & mask) | or, writable registers in index',
         ' * order): 0 / 3 = composite NTSC / PAL, 1 / 4 = S-video, 2 / 5 = component (525 / 625 lines). Then the',
         ' * hidden-register script (FUN_00028f04): the ADI SD script for 0/1/3/4, b7=1b for 2/5. Composite only: our',
         ' * overrides (re/NOTES.md, analog probes 6/7): 0x04 = 0xcc limited range, 0x17 = 0xa2 luma notch (no',
         ' * subcarrier dots), 0x2c = 0xce luma/chroma AGC (manual gains are half).',
         ' */', '#ifndef MXO2_ADV7181_MODES_H', '#define MXO2_ADV7181_MODES_H', '']
for i in range(6):
    lines += table('adv7181_mode%d' % i, MODES[i]) + ['']
lines += ['struct adv7181_table { const u8 (*regs)[2]; unsigned int n; };', '',
          'static const struct adv7181_table adv7181_modes[6] = {']
lines += ['\t{ adv7181_mode%d, ARRAY_SIZE(adv7181_mode%d) },' % (i, i) for i in range(6)]
lines += ['};', '']
lines += table('adv7181_hidden_sd', HIDDEN_SD) + ['']
lines += table('adv7181_hidden_comp', HIDDEN_COMP) + ['']
lines += table('adv7181_overrides', sorted(DEFAULT.items())) + ['', '#endif']
print('\n'.join(lines))
