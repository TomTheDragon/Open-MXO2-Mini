#!/usr/bin/env python3
"""Extract the AD9398 per-mode register tables from MVKAVCIO.sys.

DAT_0007e410: 12 modes x 0xae entries of {u32 index, u32 value}, loaded by FUN_00014a5c.
Index -> register address comes from notes/MVKAVCIO.chipregs.txt (FUN_000111a8).
Writes notes/AD9398.modes.txt (human readable) and tools/ad9398_modes.py (data for tools).
Usage: python3 -I tools/ad9398_tables.py
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, HERE)
from pe import PE  # noqa: E402

TABLE, NMODES, NENT, STRIDE = 0x7e410, 12, 0xae, 0x570

pe = PE(os.path.join(ROOT, 'bin', 'MVKAVCIO.sys'))


def off(va):
    for _, v, vs, raw, _ in pe.sections:
        if pe.base + v <= va < pe.base + v + vs:
            return raw + va - pe.base - v
    raise ValueError(hex(va))


regs, cur = {}, None
for line in open(os.path.join(ROOT, 'notes', 'MVKAVCIO.chipregs.txt')):
    if line.startswith('#'):
        cur = line.split()[1]
    elif cur == 'FUN_000111a8':
        m = re.search(r'idx=0x(\w+)\s+reg=0x(\w+)\s+size=\d+\s+(RO|RW)\s+(.*)', line)
        regs[int(m[1], 16)] = (int(m[2], 16), m[3], m[4].strip())

o = off(TABLE)
tabs = [[struct.unpack_from('<II', pe.data, o + m * STRIDE + 8 * i) for i in range(NENT)]
        for m in range(NMODES)]
assert all([a for a, _ in t] == [a for a, _ in tabs[0]] for t in tabs), 'index order differs'

rows = []
for i, (idx, _) in enumerate(tabs[0]):
    reg, rw, name = regs[idx]
    rows.append((reg, rw, name, [t[i][1] for t in tabs]))

with open(os.path.join(ROOT, 'notes', 'AD9398.modes.txt'), 'w') as f:
    f.write('# AD9398 per-mode tables (MVKAVCIO DAT_0007e410, FUN_00014a5c writes only RW entries)\n')
    f.write('# reg rw name%s %s\n' % (' ' * 31, ' '.join('m%-2d' % m for m in range(NMODES))))
    for reg, rw, name, vals in rows:
        f.write('%02x  %s %-35s %s\n' % (reg, rw, name[:35], ' '.join('%02x ' % v for v in vals)))

with open(os.path.join(HERE, 'ad9398_modes.py'), 'w') as f:
    f.write('"""AD9398 mode tables, generated by ad9398_tables.py from MVKAVCIO DAT_0007e410.\n\n'
            'MODES[i] = [(reg, value), ...] for the writable registers in the order Windows writes\n'
            'them (FUN_00014a5c). Mode 0 is loaded at chip creation; FUN_00014b28 picks 1..11 by\n'
            'format: 480 lines 1/2, 576 3/4, 1080i 5/6, 720p 7/8, 1080p 9/10/11.\n"""\n')
    f.write('MODES = [\n')
    for m in range(NMODES):
        f.write('    %r,\n' % [(r, v[m]) for r, rw, _, v in rows if rw == 'RW'])
    f.write(']\n')
print('rows', len(rows), 'writable', sum(r[1] == 'RW' for r in rows))
