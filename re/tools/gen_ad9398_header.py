#!/usr/bin/env python3
"""Write driver/ad9398_modes.h from ad9398_modes.MODES (no root needed).

Usage: python3 -I gen_ad9398_header.py [out.h]   (default ../../driver/ad9398_modes.h)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ad9398_modes import MODES  # noqa: E402

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                          '..', '..', 'driver', 'ad9398_modes.h')
n = len(MODES[0])
assert all(len(m) == n for m in MODES)
lines = ['/* SPDX-License-Identifier: GPL-2.0 */',
         '/*',
         ' * AD9398 HDMI receiver register tables, one per video mode, generated by',
         ' * re/tools/gen_ad9398_header.py from MVKAVCIO.sys DAT_0007e410 (FUN_00014a5c writes them',
         ' * in this order). Mode 0 is loaded at chip creation; FUN_00014b28 picks 1..11 by format:',
         ' * 480 lines 1/2, 576 3/4, 1080i 5/6, 720p 7/8, 1080p 9/10/11.',
         ' */',
         '#ifndef MXO2_AD9398_MODES_H',
         '#define MXO2_AD9398_MODES_H',
         '',
         '#define AD9398_NUM_MODES %d' % len(MODES),
         '#define AD9398_MODE_REGS %d' % n,
         '',
         'static const u8 ad9398_modes[AD9398_NUM_MODES][AD9398_MODE_REGS][2] = {']
for i, m in enumerate(MODES):
    lines.append('\t[%d] = {' % i)
    pairs = ['{ 0x%02x, 0x%02x }' % rv for rv in m]
    for j in range(0, len(pairs), 6):
        lines.append('\t\t' + ', '.join(pairs[j:j + 6]) + ',')
    lines.append('\t},')
lines += ['};', '', '#endif', '']
open(out, 'w').write('\n'.join(lines))
print('wrote', out, len(MODES), 'modes x', n, 'registers')
